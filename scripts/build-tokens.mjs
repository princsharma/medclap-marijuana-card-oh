// Generates app/tokens.css from brand/tokens.json (single source of truth, mirrored in Figma variables).
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('../brand/tokens.json', import.meta.url)));
const v = k => k.replace('/', '-');
const lines = [':root {'];
for (const [k, hex] of Object.entries(t.primitives)) lines.push(`  --${v(k)}: ${hex};`);
for (const [k, ref] of Object.entries(t.color)) lines.push(`  --color-${v(k)}: var(--${v(ref)});`);
for (const [k, px] of Object.entries(t.spacing)) lines.push(`  --space-${k}: ${px / 16}rem;`);
for (const [k, px] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${px}px;`);
lines.push(`  --font-display: var(--font-bricolage), system-ui, sans-serif;`);
lines.push(`  --font-body: var(--font-figtree), system-ui, sans-serif;`);
lines.push('}', '');
for (const [k, s] of Object.entries(t.type)) {
  lines.push(`.type-${k} {`, `  font-family: var(--font-${s.family});`, `  font-weight: ${s.weight};`,
    `  font-size: ${s.size / 16}rem;`, `  line-height: ${s.line / s.size};`, `  letter-spacing: ${s.tracking}px;`);
  if (s.uppercase) lines.push('  text-transform: uppercase;');
  lines.push('}');
}
lines.push('', '@media (max-width: 600px) {', '  .type-display { font-size: 2.5rem; }', '  .type-h1 { font-size: 2.125rem; }', '  .type-h2 { font-size: 1.625rem; }', '}');
writeFileSync(new URL('../app/tokens.css', import.meta.url), '/* Generated by scripts/build-tokens.mjs — do not edit by hand. */\n' + lines.join('\n') + '\n');
console.log('tokens.css written');
